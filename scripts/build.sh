#!/bin/bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SWIFT_SDK="${SWIFT_SDK:-$(xcrun --sdk macosx --show-sdk-path)}"
BUILD_DIR="${OLDLOCAL_BUILD_DIR:-$(mktemp -d "${TMPDIR:-/tmp}/oldlocal-build.XXXXXX")}"
APP="$BUILD_DIR/OldLocal.app"
mkdir -p "$BUILD_DIR/module-cache" "$APP/Contents/MacOS" "$APP/Contents/Resources/backend" "$APP/Contents/Library/HelperTools"
SWIFT=(/usr/bin/xcrun swiftc -sdk "$SWIFT_SDK" -swift-version 5 -target arm64-apple-macos15.0 -module-cache-path "$BUILD_DIR/module-cache")
S="$ROOT/Sources"
"${SWIFT[@]}" -framework Security "$S/helper/HelperProtocol.swift" "$S/helper/HelperMain.swift" -o "$APP/Contents/Library/HelperTools/OldLocalHelper"
"${SWIFT[@]}" -framework Security "$S/helper/HelperProtocol.swift" "$S/helper/Signing.swift" "$S/helper/InstallerMain.swift" -o "$APP/Contents/Library/HelperTools/OldLocalInstaller"
"${SWIFT[@]}" "$S/preferences/PreferenceAccess.swift" "$S/preferences/PreferencesCLI.swift" -o "$APP/Contents/Resources/backend/LocationPreferences"
"${SWIFT[@]}" -framework AppKit -framework MapKit -framework Security "$S"/*.swift "$S/helper/HelperProtocol.swift" "$S/helper/HelperClient.swift" "$S/helper/Signing.swift" -o "$APP/Contents/MacOS/MacLocation"
cp "$ROOT/Resources/Info.plist" "$APP/Contents/Info.plist"
cp "$ROOT/Resources/AppIcon.icns" "$ROOT/Resources/OldleePortrait.png" "$APP/Contents/Resources/"
cp "$ROOT/Backend/"*.py "$ROOT/Backend/LICENSE" "$APP/Contents/Resources/backend/"
cp "$ROOT/LICENSE" "$APP/Contents/Resources/LICENSE"
cp "$ROOT/THIRD_PARTY_NOTICES.md" "$APP/Contents/Resources/"
xattr -cr "$APP"
IDENTITY="${SIGNING_IDENTITY:--}"
codesign --force --sign "$IDENTITY" --options runtime --identifier art.oldlee.oldlocal.helper "$APP/Contents/Library/HelperTools/OldLocalHelper"
codesign --force --sign "$IDENTITY" --options runtime --identifier art.oldlee.oldlocal.installer "$APP/Contents/Library/HelperTools/OldLocalInstaller"
codesign --force --sign "$IDENTITY" --options runtime --identifier art.oldlee.maclocation.preferences "$APP/Contents/Resources/backend/LocationPreferences"
codesign --force --sign "$IDENTITY" --options runtime "$APP"
codesign --verify --deep --strict "$APP"
python3 "$ROOT/scripts/package.py" "$APP" "$ROOT/dist"
printf 'Built: %s\n' "$APP"
